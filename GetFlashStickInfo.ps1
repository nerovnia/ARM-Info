#Requires -Version 5.1
<#
.SYNOPSIS
    Shows serial numbers and other details of connected USB flash drives.

.DESCRIPTION
    For every USB storage device it reports:
      - Model, vendor, product, firmware revision
      - Serial number (from the device instance ID, WMI and the Storage module)
      - USB VID / PID and the USB-level serial
      - Size, media type, partition style, health
      - Drive letters, volume labels, file systems, volume serial numbers, free space
      - First install and last connection dates (Windows 10+)
    Optionally lists every USB storage device that was ever connected (registry USBSTOR).

.PARAMETER ExportCsv
    Path to save the results as a CSV file.

.PARAMETER History
    Also list USB storage devices ever connected to this PC.

.EXAMPLE
    .\Get-UsbFlashInfo.ps1

.EXAMPLE
    .\Get-UsbFlashInfo.ps1 -ExportCsv C:\Temp\usb.csv -History
#>
[CmdletBinding()]
param(
    [string]$ExportCsv,
    [switch]$History
)

function Get-DevProp {
    param([string]$InstanceId, [string]$Key)
    try {
        (Get-PnpDeviceProperty -InstanceId $InstanceId -KeyName $Key -ErrorAction Stop).Data
    } catch { $null }
}

function Format-Size {
    param($Bytes)
    if ($null -eq $Bytes) { return $null }
    '{0:N2} GB' -f ([double]$Bytes / 1GB)
}

# --- Find USB disks (InterfaceType USB, plus UASP drives that report as SCSI) ---
$usbDiskNumbers = @()
try {
    $usbDiskNumbers = @(Get-Disk -ErrorAction Stop |
        Where-Object BusType -eq 'USB' |
        Select-Object -ExpandProperty Number)
} catch { }

$usbDrives = Get-CimInstance -ClassName Win32_DiskDrive |
    Where-Object { $_.InterfaceType -eq 'USB' -or $usbDiskNumbers -contains $_.Index } |
    Sort-Object Index

$results = foreach ($drive in $usbDrives) {
    $pnpId = $drive.PNPDeviceID

    # Serial from instance ID: USBSTOR\DISK&VEN_x&PROD_y&REV_z\<SERIAL>&0
    $instSerial = ($pnpId -split '\\')[-1] -replace '&\d+$', ''
    # If the 2nd character is '&', Windows generated the ID (device has no unique serial)
    $hasUniqueSerial = -not ($instSerial.Length -gt 1 -and $instSerial[1] -eq '&')

    $vendor   = if ($pnpId -match 'VEN_([^&\\]*)')  { ($Matches[1] -replace '_', ' ').Trim() }
    $product  = if ($pnpId -match 'PROD_([^&\\]*)') { ($Matches[1] -replace '_', ' ').Trim() }
    $revision = if ($pnpId -match 'REV_([^&\\]*)')  { $Matches[1] }

    # Walk up to the parent USB device to get VID / PID / USB serial
    $vid = $usbPid = $usbSerial = $null
    $node = $pnpId
    for ($i = 0; $i -lt 3 -and $node; $i++) {
        $node = Get-DevProp $node 'DEVPKEY_Device_Parent'
        if ($node -match '^USB\\VID_([0-9A-F]{4})&PID_([0-9A-F]{4})\\(.+)$') {
            $vid = $Matches[1].ToUpper(); $usbPid = $Matches[2].ToUpper(); $usbSerial = $Matches[3]
            break
        }
    }

    # Storage module info (Windows 8+)
    $disk = $null
    try { $disk = Get-Disk -Number $drive.Index -ErrorAction Stop } catch { }

    # Partitions -> logical volumes
    $volumes = @(foreach ($part in (Get-CimAssociatedInstance -InputObject $drive -ResultClassName Win32_DiskPartition)) {
        Get-CimAssociatedInstance -InputObject $part -ResultClassName Win32_LogicalDisk
    })

    [pscustomobject]@{
        DiskNumber          = $drive.Index
        Model               = $drive.Model
        Vendor              = $vendor
        Product             = $product
        FirmwareRevision    = $revision
        SerialNumber        = if ($hasUniqueSerial) { $instSerial } else { "$instSerial (generated by Windows - no unique serial)" }
        SerialNumber_WMI    = "$($drive.SerialNumber)".Trim()
        SerialNumber_Disk   = "$($disk.SerialNumber)".Trim()
        VID                 = $vid
        PID                 = $usbPid
        USBSerial           = $usbSerial
        MediaType           = $drive.MediaType
        BusType             = $disk.BusType
        Size                = Format-Size $drive.Size
        SizeBytes           = $drive.Size
        PartitionStyle      = $disk.PartitionStyle
        PartitionCount      = $drive.Partitions
        HealthStatus        = $disk.HealthStatus
        DriveLetters        = ($volumes.DeviceID -join ', ')
        VolumeLabels        = ($volumes.VolumeName -join ', ')
        FileSystems         = ($volumes.FileSystem -join ', ')
        VolumeSerialNumbers = ($volumes | ForEach-Object {
                                  if ($_.VolumeSerialNumber) { $_.VolumeSerialNumber.Insert(4, '-') }
                              }) -join ', '
        FreeSpace           = ($volumes | ForEach-Object { Format-Size $_.FreeSpace }) -join ', '
        FirstInstalled      = Get-DevProp $pnpId 'DEVPKEY_Device_FirstInstallDate'
        LastConnected       = Get-DevProp $pnpId 'DEVPKEY_Device_LastArrivalDate'
        PNPDeviceID         = $pnpId
    }
}

# --- Output ---
if (-not $results) {
    Write-Warning 'No USB flash drives found.'
} else {
    Write-Host "`n=== Connected USB storage devices: $(@($results).Count) ===" -ForegroundColor Cyan
    $results | Format-List

    if ($ExportCsv) {
        $results | Export-Csv -Path $ExportCsv -NoTypeInformation -Encoding UTF8
        Write-Host "Saved to $ExportCsv" -ForegroundColor Green
    }
}

# --- History of all USB storage devices ever connected ---
if ($History) {
    $regPath = 'HKLM:\SYSTEM\CurrentControlSet\Enum\USBSTOR'
    if (Test-Path $regPath) {
        $hist = Get-ChildItem $regPath | ForEach-Object {
            $deviceKey = $_.PSChildName
            Get-ChildItem $_.PSPath | ForEach-Object {
                $p = Get-ItemProperty $_.PSPath -ErrorAction SilentlyContinue
                [pscustomobject]@{
                    FriendlyName = $p.FriendlyName
                    SerialNumber = $_.PSChildName -replace '&\d+$', ''
                    Device       = $deviceKey
                }
            }
        }
        Write-Host "`n=== USB storage devices ever connected ===" -ForegroundColor Cyan
        $hist | Sort-Object FriendlyName | Format-Table -AutoSize
    } else {
        Write-Warning 'No USB storage history found in the registry.'
    }
}